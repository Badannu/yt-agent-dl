// YT Cookie Auto Sync —— 定时自动导出 Chrome 全量 cookie（Netscape 格式）
// 无需手动点击，导出结果固定覆盖保存到「下载」目录的 yt-cookies.txt

const FILENAME = "yt-cookies.txt";
const INTERVAL_MINUTES = 30;

// 把文本转成 base64 的 data URL（MV3 service worker 没有 DOM，不能用 Blob URL）
function toDataUrl(text) {
  const bytes = new TextEncoder().encode(text);
  let bin = "";
  const CHUNK = 0x8000;
  for (let i = 0; i < bytes.length; i += CHUNK) {
    bin += String.fromCharCode.apply(null, bytes.subarray(i, i + CHUNK));
  }
  return "data:text/plain;charset=utf-8;base64," + btoa(bin);
}

// 转成 Netscape HTTP Cookie File 格式
// 列：域  包含子域  路径  仅HTTPS  过期时间  名称  值
// HttpOnly 的 cookie 行要加 "#HttpOnly_" 前缀（这不是注释，是格式约定）
function toNetscape(cookies) {
  const lines = [
    "# Netscape HTTP Cookie File",
    "# Auto-generated by YT Cookie Auto Sync",
    "# 导出条目: " + cookies.length,
    "",
  ];
  for (const c of cookies) {
    const domain = c.domain || "";
    const includeSub = domain.startsWith(".") ? "TRUE" : "FALSE";
    const prefix = c.httpOnly ? "#HttpOnly_" : "";
    const secure = c.secure ? "TRUE" : "FALSE";
    // session cookie 没有 expirationDate，写成 0
    const expires = c.expirationDate ? Math.floor(c.expirationDate) : 0;
    const value = (c.value || "").replace(/\r?\n/g, "");
    lines.push(
      [prefix + domain, includeSub, c.path || "/", secure, expires, c.name, value].join("\t")
    );
  }
  return lines.join("\n") + "\n";
}

async function exportCookies(reason) {
  try {
    // 关键：getAll({}) 返回整个 profile 的全量 cookie，
    // 若只对单个 URL 取，会漏掉 host-only 域（如不带 www 的 youtube.com）的
    // LOGIN_INFO / SID 等登录态 cookie
    const cookies = await chrome.cookies.getAll({});
    const text = toNetscape(cookies);

    const hasLogin = cookies.some((c) => c.name === "LOGIN_INFO");
    if (!hasLogin) {
      console.warn("[yt-cookie] 未发现 LOGIN_INFO，Chrome 可能未登录 Google");
    }

    await chrome.downloads.download({
      url: toDataUrl(text),
      filename: FILENAME,
      conflictAction: "overwrite", // 覆盖同名文件，不会攒出 (1)(2)(3)
      saveAs: false,
    });

    await chrome.storage.local.set({
      lastExport: Date.now(),
      count: cookies.length,
      hasLogin,
      reason: reason || "",
    });
    console.log("[yt-cookie] 已导出 " + cookies.length + " 条 -> " + FILENAME);
  } catch (e) {
    console.error("[yt-cookie] 导出失败", e);
    await chrome.storage.local.set({ lastError: String(e) });
  }
}

chrome.runtime.onInstalled.addListener(() => {
  chrome.alarms.create("autoExport", {
    periodInMinutes: INTERVAL_MINUTES,
  });
  exportCookies("install");
});

chrome.runtime.onStartup.addListener(() => {
  exportCookies("startup");
});

chrome.alarms.onAlarm.addListener((alarm) => {
  if (alarm.name === "autoExport") {
    exportCookies("alarm");
  }
});

// 点扩展图标时立即导出一次，方便排查
chrome.action.onClicked.addListener(() => exportCookies("manual"));

// 供 popup 的「立即导出」按钮调用
chrome.runtime.onMessage.addListener((msg, _sender, sendResponse) => {
  if (msg && msg.action === "export") {
    exportCookies("popup")
      .then(() => sendResponse({ ok: true }))
      .catch(() => sendResponse({ ok: false }));
    return true; // 保持消息通道，等待异步响应
  }
});
